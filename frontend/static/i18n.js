// 语言切换器类 - Language Switcher Class
class I18n {
  constructor() {
    this.currentLang = this.detectLanguage();
    this.translations = translations;
    this.init();
  }
  
  // 检测浏览器语言 - Detect browser language
  detectLanguage() {
    // 首先检查 localStorage - Check localStorage first
    const saved = localStorage.getItem('dltk_lang');
    if (saved && window.translations[saved]) return saved;
    
    // 检测浏览器语言 - Detect browser language
    const browserLang = navigator.language || navigator.userLanguage;
    const langCode = browserLang.split('-')[0].toLowerCase();
    
    // 语言映射 - Language mapping
    const langMap = {
      'en': 'en',
      'zh': 'zh',
      'es': 'es',
      'pt': 'pt',
      'id': 'id'
    };
    
    return langMap[langCode] || 'en';
  }
  
  // 设置语言 - Set language
  setLanguage(lang) {
    if (!window.translations[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('dltk_lang', lang);
    this.updatePage();
    this.updateActiveButton();
  }
  
  // 获取翻译 - Get translation
  t(key) {
    return window.translations[this.currentLang][key] || window.translations['en'][key] || key;
  }
  
  // 初始化 - Initialize
  init() {
    // 等待DOM加载完成 - Wait for DOM to load
    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', () => {
        this.updatePage();
        this.updateActiveButton();
      });
    } else {
      this.updatePage();
      this.updateActiveButton();
    }
  }
  
  // 更新页面内容 - Update page content
  updatePage() {
    // 更新所有带 data-i18n 属性的元素 - Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = this.t(key);
      
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translation;
      } else if (el.tagName === 'BUTTON') {
        // 按钮内容可能包含 spinner - Button may contain spinner
        const textSpan = el.querySelector('.btn-text');
        if (textSpan) {
          textSpan.textContent = translation;
        } else {
          el.textContent = translation;
        }
      } else {
        el.textContent = translation;
      }
    });
    
    // 更新页面标题 - Update page title (if data-i18n-title exists)
    const titleKey = document.body.getAttribute('data-i18n-title');
    if (titleKey) {
      document.title = this.t(titleKey);
    }
    
    // 更新 meta description - Update meta description
    const metaDescKey = document.body.getAttribute('data-i18n-description');
    if (metaDescKey) {
      const metaDesc = document.querySelector('meta[name="description"]');
      if (metaDesc) metaDesc.content = this.t(metaDescKey);
    }
  }
  
  // 更新激活的语言按钮 - Update active language button
  updateActiveButton() {
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.remove('active');
      if (btn.dataset.lang === this.currentLang) {
        btn.classList.add('active');
      }
    });
  }
}

// 创建全局实例 - Create global instance
const i18n = new I18n();
i18n.init(); // 立即初始化

